import {chromium} from 'file:///C:/Users/fuweicheng/.codex/skills/node_modules/playwright/index.mjs';
import fs from 'node:fs';
import {createHash} from 'node:crypto';
const base=(process.env.CODEX_BASE_URL||'http://127.0.0.1:4173').replace(/\/$/,''),directory=new URL('../assets/codex/',import.meta.url);
fs.mkdirSync(directory,{recursive:true});
const browser=await chromium.launch({headless:true}),page=await browser.newPage();
try{
 // Blank same-origin document: use the existing renderer once at build time.
 await page.route('**/__codex-export.html',route=>route.fulfill({contentType:'text/html',body:'<!doctype html><title>Codex export</title>'}));
 await page.goto(`${base}/__codex-export.html`);
 const previews=await page.evaluate(async()=>{
  const [{CODEX_ENTRIES},{loadCodexArt,paintCodexArt},{codexImageKey}]=await Promise.all([import('./src/coop/codex-data.js'),import('./src/coop/codex-art.js'),import('./src/coop/codex-image-key.js')]);
  await loadCodexArt();const images=new Map(),canvas=document.createElement('canvas');canvas.width=640;canvas.height=380;
  for(const entry of CODEX_ENTRIES){const key=codexImageKey(entry.art);if(images.has(key))continue;paintCodexArt(canvas,entry);const data=canvas.toDataURL('image/webp',.9);if(!data.startsWith('data:image/webp;'))throw Error('WebP export unavailable');images.set(key,data.split(',')[1]);}
  return [...images];
 });
 const files={};let bytes=0;
 for(const [key,data]of previews){const image=Buffer.from(data,'base64'),hash=createHash('sha256').update(image).digest('hex').slice(0,12),file=`${key}-${hash}.webp`;fs.writeFileSync(new URL(file,directory),image);files[key]=file;bytes+=image.length;}
 fs.writeFileSync(new URL('../src/coop/codex-preview-files.js',import.meta.url),`// Generated by npm run build:codex. Original artwork, rendered at 640 x 380.\nexport const CODEX_PREVIEW_FILES=Object.freeze(${JSON.stringify(files,null,2)});\n`);
 console.log(JSON.stringify({previews:previews.length,bytes,maxBytes:Math.max(...previews.map(([,data])=>Buffer.from(data,'base64').length))}));
}finally{await browser.close();}
